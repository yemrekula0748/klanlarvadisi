<?php

namespace App\Console\Commands;

use App\Models\BuildingType;
use App\Models\TroopType;
use Illuminate\Console\Command;
use Illuminate\Support\Str;

/**
 * Sunucudaki tanımları Unity istemcisine C# olarak aktarır.
 *
 * Dünya bölgeleri, biyom renkleri ve ızgara ayarları hem sunucuda hem
 * istemcide gerekir. Elle iki yerde tutmak yerine `config/` tek doğruluk
 * kaynağıdır ve bu komut C# karşılığını üretir.
 *
 *   php artisan game:export-unity
 */
class ExportUnityCommand extends Command
{
    protected $signature = 'game:export-unity
        {--path= : Unity istemcisinin Scripts klasörü}';

    protected $description = 'Dünya bölgelerini ve oyun sabitlerini Unity için C# olarak dışa aktarır';

    public function handle(): int
    {
        $base = $this->option('path')
            ?: base_path('unity-client/Assets/Scripts');

        if (! is_dir($base)) {
            $this->error("Unity klasörü bulunamadı: {$base}");

            return self::FAILURE;
        }

        $this->bolgeleriYaz($base);
        $this->sabitleriYaz($base);

        $this->info('Unity dosyaları güncellendi.');
        $this->line('  World/BolgeTanimlari.cs');
        $this->line('  Core/OyunSabitleri.cs');

        return self::SUCCESS;
    }

    private function bolgeleriYaz(string $base): void
    {
        $rows = [];

        foreach (config('regions', []) as $r) {
            $t = $r['terrain'] ?? ['e' => 0.5, 't' => 0.5, 'm' => 0.5, 'strength' => 0.0];
            $lore = $this->csharpString($r['lore']);

            $rows[] = sprintf(
                "            new(\"%s\", %s, \"%s\", %sf, %sf, %sf, %sf, %sf, %sf, %sf, \"%s\",\n                %s),",
                $r['key'],
                $this->csharpString($r['name']),
                $r['biome'],
                $r['at'][0], $r['at'][1], $r['radius'],
                $t['e'], $t['t'], $t['m'], $t['strength'] ?? 0.88,
                $r['color'],
                $lore
            );
        }

        $body = implode("\n", $rows);

        $content = <<<CS
// <auto-generated>
//   Bu dosya `php artisan game:export-unity` ile üretilmiştir.
//   Elle düzenlemeyin — kaynak: config/regions.php
// </auto-generated>

using System.Collections.Generic;

namespace KlanlarVadisi.World
{
    /// <summary>
    /// Dünyanın adı olan bölgeleri. Hem haritada etiket olarak gösterilir
    /// hem de araziyi kendi karakterine büker (Kızıl Çöl gerçekten çöldür).
    /// </summary>
    public readonly struct BolgeTanimi
    {
        public readonly string Key;
        public readonly string Ad;
        public readonly string Biyom;
        public readonly float AtX, AtY, Radius;
        public readonly float E, T, M;
        public readonly float Strength;
        public readonly string Renk;
        public readonly string Efsane;

        public BolgeTanimi(string key, string ad, string biyom,
            float atX, float atY, float radius,
            float e, float t, float m, float strength, string renk, string efsane)
        {
            Key = key; Ad = ad; Biyom = biyom;
            AtX = atX; AtY = atY; Radius = radius;
            E = e; T = t; M = m; Strength = strength;
            Renk = renk; Efsane = efsane;
        }
    }

    public static class BolgeTanimlari
    {
        public static readonly List<BolgeTanimi> Hepsi = new()
        {
{$body}
        };
    }
}

CS;

        file_put_contents($base.'/World/BolgeTanimlari.cs', $content);
    }

    private function sabitleriYaz(string $base): void
    {
        $grid = config('game.grid.size');
        $margin = config('game.grid.margin');
        $tickRate = config('game.battle.tick_rate');
        $maxDuration = config('game.battle.max_duration');
        $prep = config('game.battle.preparation');
        $seed = config('game.world.seed');
        $w = config('game.world.width');
        $h = config('game.world.height');
        $chunk = config('game.world.chunk');
        $version = config('game.version');

        // Bina ve asker anahtarlarını sabit olarak ver: istemcide yazım
        // hatası derleme zamanında yakalanır.
        $buildingKeys = BuildingType::orderBy('sort')->pluck('key')
            ->map(fn ($k) => '        public const string '.Str::studly($k).' = "'.$k.'";')
            ->implode("\n");

        $troopKeys = TroopType::orderBy('sort')->pluck('key')
            ->map(fn ($k) => '        public const string '.Str::studly($k).' = "'.$k.'";')
            ->implode("\n");

        $content = <<<CS
// <auto-generated>
//   Bu dosya `php artisan game:export-unity` ile üretilmiştir.
//   Elle düzenlemeyin — kaynak: config/game.php
// </auto-generated>

namespace KlanlarVadisi.Core
{
    /// <summary>
    /// Sunucuyla paylaşılan oyun sabitleri. İstemci bu değerleri varsayar;
    /// sunucu katalog isteğinde aynılarını döndürür.
    /// </summary>
    public static class OyunSabitleri
    {
        public const string Surum = "{$version}";

        /// <summary>Oba ızgarasının kenar uzunluğu (kare).</summary>
        public const int IzgaraBoyu = {$grid};

        /// <summary>Kenarda bina kurulamayan şerit (asker iniş alanı).</summary>
        public const int IzgaraKenari = {$margin};

        /// <summary>Savaş simülasyonunun saniyedeki adım sayısı.</summary>
        public const int SavasAdimHizi = {$tickRate};

        /// <summary>Bir savaşın azami süresi (saniye).</summary>
        public const int SavasAzamiSure = {$maxDuration};

        /// <summary>Saldırı öncesi asker indirme süresi (saniye).</summary>
        public const int SavasHazirlik = {$prep};

        /* --------------------------- Dünya --------------------------- */

        public const int DunyaTohumu = {$seed};
        public const int DunyaGenisligi = {$w};
        public const int DunyaYuksekligi = {$h};
        public const int DunyaParcaBoyu = {$chunk};
    }

    /// <summary>Bina anahtarları — yazım hatası derlemede yakalanır.</summary>
    public static class Binalar
    {
{$buildingKeys}
    }

    /// <summary>Asker anahtarları.</summary>
    public static class Askerler
    {
{$troopKeys}
    }
}

CS;

        file_put_contents($base.'/Core/OyunSabitleri.cs', $content);
    }

    private function csharpString(string $s): string
    {
        $s = str_replace(["\\", '"', "\n", "\r"], ["\\\\", '\"', ' ', ''], $s);

        return '"'.trim(preg_replace('/\s+/', ' ', $s)).'"';
    }
}
